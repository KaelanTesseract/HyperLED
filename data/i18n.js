let currentLang = localStorage.getItem('hyperled_lang') || 'de';

function setLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
        localStorage.setItem('hyperled_lang', lang);
        applyTranslations();
        
        // Dispatch custom event for dynamic JS elements
        document.dispatchEvent(new Event('languageChanged'));
    }
}

function applyTranslations() {
    const dict = translations[currentLang];
    if (!dict) return;

    document.documentElement.lang = currentLang;

    // Names for controls that show only an icon or a colour - read by screen readers.
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (dict[key]) el.setAttribute('aria-label', dict[key]);
    });

    // Hint text inside an empty field - a placeholder is a text like any other.
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) el.setAttribute('placeholder', dict[key]);
    });

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'OPTGROUP') {
                el.label = dict[key];
            } else if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
                el.value = dict[key];
            } else {
                el.innerHTML = dict[key];
            }
        }
    });
}

// t('key') returns the translation, t('key', {ver: '1.2'}) also fills in {ver} placeholders.
function t(key, vars) {
    const dict = translations[currentLang] || {};
    let text = dict[key] || key;
    if (vars) {
        Object.keys(vars).forEach(name => {
            text = text.split('{' + name + '}').join(vars[name]);
        });
    }
    return text;
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    
    // Bind language select if it exists
    const langSelect = document.getElementById('languageSelect');
    if (langSelect) {
        langSelect.value = currentLang;
        langSelect.addEventListener('change', (e) => {
            setLanguage(e.target.value);
        });
    }
});
